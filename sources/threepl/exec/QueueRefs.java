    /**
     * Check if there are any queue references.
     * @return   true if there are no queue references
     */
    public boolean isEmpty () {
        for (SetPair sp : read_ands)
            if (!sp.hasNoQueues())
                return(false);
        return(write_queues.isEmpty() && read_queues.isEmpty());
    }
    
