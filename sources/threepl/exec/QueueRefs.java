    /**
     * Check if there is a single queue write reference only (i.e.
     * there are no queue subscripts to a LHS queue variable).
     * @return   true if there is a single queue write reference only
     */
    public boolean isSingleWrite () {
        return(read_queues.isEmpty() && (write_queues.size() == 1));
    }
    
    /**
     * AND a queue variable availability requirement.
     * @param   v is the queue variable
     * @param   write is true if queue write availability (rather than read)
     *          is required
     * @param   loc is the source file location
     */
    public void and_set (Queue v, boolean write, SrcLoc loc) {
        clearAvails();
        if (write) {
            write_queues.add(v);
        } else {
            read_queues.add(v);
            if (read_ands.isEmpty()) {
                HashSet<Queue> ps = new HashSet<Queue>();
                HashSet<CondSig> ss = new HashSet<CondSig>();
                ps.add(v);
                read_ands.add(new SetPair(ps, ss));
            } else {
                for (SetPair sp : read_ands)
                    sp.queues.add(v);
            }
            optimise();
            resolveCounts();
        }
    }
    
    /**
     * If there are queue read entries, AND a conditional signal to them.
     * @param   tdev is the conditional signal
     * @param   inv is true if the signal is to be inverted
     * @param   loc is the source file location
     */
    public void and (TDEVar tdev, boolean inv, SrcLoc loc) {
        if (read_queues.isEmpty())
            return;
        if (ubrqueues != 0)
            throw new ExEx("statement has unbuffered queue in ?: operator", loc);
        clearAvails();
        for (SetPair sp : read_ands)
            sp.sigs.add(new CondSig(tdev, inv));
        optimise();
    }
    
    /**
     * AND a queues reference unless this queue reference has no read_ands terms,
     * in which case copy the read_ands terms from the argument queue reference.
     * @param   pr is the queues reference
     * @param   loc is the source file location
     */
    public void and_set (QueueRefs pr, SrcLoc loc) {
        if (pr.isEmpty())
            return;

        if (isEmpty()) {
            write_queues.addAll(pr.write_queues);
            read_queues.addAll(pr.read_queues);
            Iterator<?>    it = pr.read_ands.iterator();
            while (it.hasNext())
                read_ands.add(new SetPair((SetPair)it.next()));
            bqavails.putAll(pr.bqavails);
            ubqwavails = pr.ubqwavails;
            ubqravails = pr.ubqravails;
            syncavails.putAll(pr.syncavails);
            ravails.putAll(pr.ravails);
            resolveCounts();
            return;
        }
        
        clearAvails();

        write_queues.addAll(pr.write_queues);

        if (pr.read_queues.isEmpty()) {
            resolveCounts();
            return;
        }
            
        read_queues.addAll(pr.read_queues);
        ArrayList<SetPair>  ra = new ArrayList<SetPair>();
        if (read_ands.isEmpty())
            read_ands.addAll(pr.read_ands);
        else {
            for (SetPair sp1 : read_ands) {
                for (SetPair sp2 : pr.read_ands) {
                    HashSet<Queue> ps = new HashSet<Queue>();
                    HashSet<CondSig> ss = new HashSet<CondSig>();
                    ps.addAll(sp1.queues);
                    ps.addAll(sp2.queues);
                    ss.addAll(sp1.sigs);
                    ss.addAll(sp2.sigs);
                    ra.add(new SetPair(ps, ss));
                }
            }
            read_ands = ra;
        }
        
        read_av_queues.addAll(pr.read_av_queues);
        write_av_queues.addAll(pr.write_av_queues);
        
        optimise();
        resolveCounts();
    }
    
