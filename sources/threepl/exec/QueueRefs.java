    /**
     * OR a queues reference.
     * @param   pr is the queues reference
     * @param   loc is the source file location
     */
    public void or (QueueRefs pr, SrcLoc loc) {
        if (pr.isEmpty())
            return;

        if (ubrqueues != 0)
            throw new ExEx("statement has unbuffered queue in ?: operator", loc);
        Iterator<?>    it;
        if (isEmpty()) {
            write_queues.addAll(pr.write_queues);
            read_queues.addAll(pr.read_queues);
            it = pr.read_ands.iterator();
            while (it.hasNext())
                read_ands.add(new SetPair((SetPair)it.next()));
            bqavails.putAll(pr.bqavails);
            ubqwavails = pr.ubqwavails;
            ubqravails = pr.ubqravails;
            syncavails.putAll(pr.syncavails);
            ravails.putAll(pr.ravails);
            resolveCounts();
            return;
        }

        clearAvails();
        
        write_queues.addAll(pr.write_queues);

        read_queues.addAll(pr.read_queues);
        it = pr.read_ands.iterator();
        while (it.hasNext())
            read_ands.add(new SetPair((SetPair)it.next()));
        resolveCounts();
    }

    /**
     * Test a QueueRefs against this one for an overlap of the set of
     * queue reads. If there is an overlap, return true.
     * @param   pr the QueueRefs to test against this one
     * @return  true if an overlap of reads, false otherwise
     */
    public boolean readOverlap (QueueRefs pr) {
        HashSet<?>    s = pr.getReads();
        int                 init_size = s.size();
        if (init_size == 0)
            return(false); // body has no queue reads
        s = (HashSet<?>)s.clone();
        HashSet<Queue> ts = read_queues;
        if (ts.size() == 0)
            return(false); // test expression has no queue reads
        for (Queue p: ts)  // iterate through test expression queue reads
            s.remove(p);    // remove from the body set if present
        // if the set of body queue reads is unchanged, OK
        if (s.size() == init_size)
            return(false);
        // if the set of body queue reads is now empty and
        // the body queue writes set is empty, OK
        if ((s.size() == 0) && (pr.getWrites().size() == 0))
            return(false);
        
        return(true);
    }
    
    /**
     * Optimise sum of products.
     */
    private void optimise () {
        int         len;
        SetPair[]   a;
        Iterator<SetPair>    it;

        // Simplify p1 & p2 & ... & s | p1 & p2 &  ... & !s .
        len = read_ands.size();
        a = new SetPair[len];
        a = read_ands.toArray(a);
        for (int i=0 ; i<len ; i++) {
            if (a[i].remove)
                continue;
            HashSet<?> psi = a[i].queues;
            HashSet<?> ssi = a[i].sigs;
            for (int j=i+1 ; j<len ; j++) {
                if (a[j].remove)
                    continue;
                HashSet<?> psj = a[j].queues;
                HashSet<?> ssj = a[j].sigs;
                if (psi.equals(psj) && inversionof(ssi, ssj)) {
                    a[j].remove = true;
                    ssi.clear();
                }
            }
        }
        it = read_ands.iterator();
        while (it.hasNext()) {
            SetPair sp = it.next();
            if (sp.remove)
                it.remove();
        }

        // Eliminate superset terms.
        len = read_ands.size();
        a = new SetPair[len];
        a = read_ands.toArray(a);
        for (int i=0 ; i<len ; i++) {
            if (a[i].remove)
                continue;
            HashSet<?> psi = a[i].queues;
            HashSet<?> ssi = a[i].sigs;
            for (int j=i+1 ; j<len ; j++) {
                if (a[j].remove)
                    continue;
                if (a[j].queues.containsAll(psi) && a[j].sigs.containsAll(ssi))
                    a[j].remove = true;
            }
        }
        it = read_ands.iterator();
        while (it.hasNext()) {
            SetPair sp = it.next();
            if (sp.remove)
                it.remove();
        }
    }
    
    private static boolean inversionof (HashSet<?> ss1, HashSet<?> ss2) {
        if ((ss1.size() != 1) || (ss2.size() != 1))
            return(false);
        Iterator<?>    it;
        it = ss1.iterator();
        CondSig     sig1 = (CondSig)it.next();
        it = ss2.iterator();
        CondSig     sig2 = (CondSig)it.next();
        return(sig1.inversionof(sig2));
    }
   
