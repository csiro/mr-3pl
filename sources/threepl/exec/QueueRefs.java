    /**
     * Return a deep copy of this queues reference.
     * @return   the copy of this class
     */
    public QueueRefs copy () {
        QueueRefs    p = new QueueRefs();

        p.write_queues.addAll(write_queues);
        p.read_queues.addAll(read_queues);
        p.write_av_queues.addAll(write_av_queues);
        p.read_av_queues.addAll(read_av_queues);
        p.bqavails.putAll(bqavails);
        p.ubqwavails = ubqwavails;
        p.ubqravails = ubqravails;
        p.syncavails.putAll(syncavails);
        p.ravails.putAll(ravails);
        p.brqueues = brqueues;
        p.bwqueues = bwqueues;
        p.ubrqueues = ubrqueues;
        p.ubwqueues = ubwqueues;

        Iterator<SetPair>    it = read_ands.iterator();
        while (it.hasNext())
            p.read_ands.add(new SetPair(it.next()));

        return(p);
    }
    
    /**
     * Get the availability signal for buffered queues in this queues reference, or null.
     * Null is returned if the queue reference is empty.
     * @param   module_scope is the scope we are in
     * @param   checkedqueues specifies queues which don't need availability checking
     * @param   loc is the source file location
     * @return  the availability value
     */
    public Val getBQAvail (Scope module_scope, QueueRefs checkedqueues, SrcLoc loc) {
        if (read_queues.isEmpty() && write_queues.isEmpty())
            return(null);
        if (module_scope == null)
            module_scope = getModuleScope();
        if (bqavails.containsKey(module_scope))
            return(bqavails.get(module_scope));
        
        TDEVar  tdev = tdelist.signal("AV", loc);
        TDE     or = new TDE(TDEType.OR, loc);
        Val     val = new Val(null, Mode.VALUE, tdev, loc);
        
        if (read_queues.isEmpty() && !write_queues.isEmpty()) {
            // Have only writes to a queues.
            TDE     and = new TDE(TDEType.AND, loc);
            for (Queue p : write_queues) {
                if (p.getBufferSize() == 0)
                    continue;
                // add the queue to the input (write) domain variables for the Val
                val.addIVar(p);
                // If this queue is not already checked add it to the AND gate
                if ((checkedqueues == null) || !checkedqueues.write_av_queues.contains(p))
                    and.add2i(p.getWriteAvailSig(loc));
            }
            if (and.getInputs().size() != 0)
                or.add2i(and.finish());
        } else if (!read_queues.isEmpty()) {
            // Have reads from queues and possibly writes to a queue.
            boolean     skip_check = false;
            if (checkedqueues != null) {
                // More than 1 entry in either means ORed conditions
                // in which case cannot use checkedqueues.
                // Zero entry in either means no optimisation to be done
                // so don't try.
                if ((read_ands.size() != 1) || (checkedqueues.read_ands.size() != 1))
                    checkedqueues = null;
                else {
                    SetPair sp1 = read_ands.get(0);
                    SetPair sp2 = checkedqueues.read_ands.get(0);
                    if (sp1.sigs.isEmpty() && sp2.sigs.isEmpty()) {
                        // Have single entry in both set pair lists and
                        // the signal sets for both are empty - so
                        // see if the body read queues set is equal to or a
                        // subset of the read checked queue set. If true, all
                        // queue reads have already been checked and no further
                        // queue read availability checking is needed.
                        Iterator<?>    it = sp1.queues.iterator();
                        skip_check = true;
                        while (it.hasNext()) {
                            Queue    p = (Queue)it.next();
                            if (sp2.queues.contains(p) || checkedqueues.read_av_queues.contains(p))
                                continue;
                            skip_check = false;
                            break;
                        }
                    }
                }
            }
            for (SetPair sp : read_ands) {
                TDE     and = new TDE(TDEType.AND, loc);
                for (Queue q : write_queues ) {
                    if (q.getBufferSize() == 0)
                        continue;
                    val.addIVar(q);
                    if ((checkedqueues == null) || !checkedqueues.write_av_queues.contains(q)) {
                        and.add2i(q.getWriteAvailSig(loc));
                    }
                }
                for (Queue q : sp.queues) {
                    if (q.getBufferSize() == 0)
                        continue;
                    val.addOVar(q);
                    if (!skip_check && ((checkedqueues == null) || !checkedqueues.read_av_queues.contains(q)))
                        and.add2i(q.getReadAvailSig(module_scope, loc));
                }
                for (CondSig cs : sp.sigs)
                    and.add2i(cs.getSignal(loc));

                if (and.getInputs().size() != 0)
                    or.add2i(and.finish());
            }
        }

        if (or.getInputs().size() == 0)
            return(null);

        or.add2o(tdev);
        tdelist.addTDE(or);
        bqavails.put(module_scope, val);
        return(val);
    }  
